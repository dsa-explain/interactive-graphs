const PYODIDE_MODULE = "https://cdn.jsdelivr.net/pyodide/v0.25.0/full/pyodide.mjs";

let _pyodidePromise = null;

function getPyodide() {
  if (!_pyodidePromise) {
    _pyodidePromise = (async () => {
      const { loadPyodide } = await import(/* @vite-ignore */ PYODIDE_MODULE);
      return loadPyodide({ indexURL: PYODIDE_INDEX });
    })();
  }
  return _pyodidePromise;
}

export const DEFAULT_START = [8, 20];
export const DEFAULT_COLOR = "#ff6b4a";

export function clonePixelArray(grid = PIXEL_ARRAY) {
  return (grid ?? []).map((row) => row.slice());
}

export function floodFillStarterCode() {
  return `def floodFill(pixel_array, start, color):
    """Fill the connected region of start with color, in place.

    pixel_array: 2D list of hex colour strings
    start: (row, col)
    color: hex string to paint with
    """
    row, col = start
    original = pixel_array[row][col]
    if original == color:
        return

    rows, cols = len(pixel_array), len(pixel_array[0])

    # 4-connected neighbours: (r-1, c), (r+1, c), (r, c-1), (r, c+1)
    # Visit every cell that still has the original colour and set it to color.

`;
}

function luminance(hex) {
  const n = String(hex ?? "").replace("#", "");
  if (n.length < 6) return 0;
  const r = parseInt(n.slice(0, 2), 16);
  const g = parseInt(n.slice(2, 4), 16);
  const b = parseInt(n.slice(4, 6), 16);
  if ([r, g, b].some((x) => Number.isNaN(x))) return 0;
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255;
}

function paintCellEl(el, hex) {
  const color = hex || "#000000";
  el.style.backgroundColor = color;
  el.dataset.hex = color;
  el.title = color;
  el.style.color = luminance(color) > 0.62 ? "#1a1a1a" : "#f7f7f7";
  el.textContent = color;
}

function cellKey(r, c) {
  return `${r},${c}`;
}

/**
 * Compact pixel-art board. Each cell's value is a hex colour; the swatch
 * is that colour. Hex text is shown when cells are large enough, otherwise
 * it lives on the tooltip / hover readout.
 */
function mountPixelBoard(container, grid, options = {}) {
  const rows = grid.length;
  const cols = grid[0]?.length ?? 0;
  const onCellClick = options.onCellClick ?? null;
  const selectable = options.selectable ?? true;

  container.innerHTML = "";
  container.classList.add("ff-scene");

  const board = document.createElement("div");
  board.className = "ff-board";
  container.appendChild(board);

  const cellEls = new Map();
  let startCell = options.start ? cellKey(options.start[0], options.start[1]) : null;
  let paintCell = null;

  function cellSizeForWidth(width) {
    if (!cols) return 8;
    const available = Math.max(160, width - 8);
    return Math.max(7, Math.min(16, Math.floor(available / cols)));
  }

  function applySize(size) {
    board.style.setProperty("--ff-cols", String(cols));
    board.style.setProperty("--ff-rows", String(rows));
    board.style.setProperty("--ff-cell-size", `${size}px`);
  }

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const el = document.createElement("div");
      el.className = "ff-cell";
      el.dataset.row = String(r);
      el.dataset.col = String(c);
      paintCellEl(el, grid[r][c]);
      if (selectable) {
        el.classList.add("ff-cell-selectable");
        el.addEventListener("click", () => onCellClick && onCellClick(r, c));
      }
      board.appendChild(el);
      cellEls.set(cellKey(r, c), el);
    }
  }

  applySize(cellSizeForWidth(container.clientWidth || options.width || 420));

  function markSpecial() {
    cellEls.forEach((el, key) => {
      el.classList.toggle("ff-cell-start", key === startCell);
      el.classList.toggle("ff-cell-paint", key === paintCell);
    });
  }
  markSpecial();

  return {
    setColor(r, c, hex) {
      const el = cellEls.get(cellKey(r, c));
      if (!el) return;
      paintCellEl(el, hex);
    },
    setGrid(next) {
      for (let r = 0; r < rows; r++) {
        for (let c = 0; c < cols; c++) {
          const el = cellEls.get(cellKey(r, c));
          if (el) paintCellEl(el, next[r][c]);
        }
      }
    },
    setStart(rc) {
      startCell = rc ? cellKey(rc[0], rc[1]) : null;
      markSpecial();
    },
    setPaint(rc) {
      paintCell = rc ? cellKey(rc[0], rc[1]) : null;
      markSpecial();
    },
    resize(width) {
      applySize(cellSizeForWidth(width));
      markSpecial();
    },
    cellAt(r, c) {
      return cellEls.get(cellKey(r, c));
    },
  };
}

function buildFloodHarness(pixelArray, start, color, userSrc) {
  const srcLit = JSON.stringify(userSrc ?? "");
  const gridLit = JSON.stringify(pixelArray);
  const startLit = JSON.stringify(start);
  const colorLit = JSON.stringify(color);
  const maxEvents = Math.max(4000, pixelArray.length * (pixelArray[0]?.length ?? 0) + 50);

  return `
import json
import sys
import io
import traceback

_user_src = ${srcLit}
_MAX_EVENTS = ${maxEvents}
_frames = []
_error = None
_stdout = io.StringIO()
_stderr = io.StringIO()

def _user_line():
    frame = sys._getframe()
    fallback = None
    while frame is not None:
        filename = frame.f_code.co_filename
        name = frame.f_code.co_name
        if filename == "<user>":
            return frame.f_lineno
        if (
            fallback is None
            and not name.startswith("_")
            and name not in ("<module>", "<genexpr>", "<lambda>")
        ):
            fallback = frame.f_lineno
        frame = frame.f_back
    return fallback

def _record(r, c, color):
    if len(_frames) >= _MAX_EVENTS:
        raise RuntimeError("TOO_MANY_ITERS")
    _frames.append({
        "r": int(r),
        "c": int(c),
        "color": color,
        "line": _user_line(),
    })

class _TraceRow(list):
    def __init__(self, r, cells):
        super().__init__(cells)
        self._r = r
    def __setitem__(self, c, value):
        if not isinstance(c, int):
            super().__setitem__(c, value)
            return
        prev = self[c] if 0 <= c < len(self) else None
        value = None if value is None else str(value)
        super().__setitem__(c, value)
        if value != prev:
            _record(self._r, c, value)

class _TraceGrid(list):
    def __init__(self, rows):
        super().__init__(_TraceRow(i, list(row)) for i, row in enumerate(rows))
    def __setitem__(self, r, value):
        if isinstance(r, int):
            super().__setitem__(r, _TraceRow(r, list(value)))
            for c, col in enumerate(self[r]):
                _record(r, c, str(col))
        else:
            super().__setitem__(r, value)

pixel_array = _TraceGrid(${gridLit})
start = tuple(${startLit})
color = ${colorLit}

_old_out, _old_err = sys.stdout, sys.stderr
_ns = {
    "pixel_array": pixel_array,
    "start": start,
    "color": color,
    "__name__": "__main__",
}
try:
    sys.stdout = _stdout
    sys.stderr = _stderr
    _code = compile(_user_src, "<user>", "exec")
    exec(_code, _ns)
    fn = _ns.get("floodFill")
    if not callable(fn):
        raise RuntimeError("Define a floodFill(pixel_array, start, color) function.")
    fn(pixel_array, start, color)
except RuntimeError as e:
    if str(e) == "TOO_MANY_ITERS":
        _error = "TOO_MANY_ITERS"
    else:
        _error = type(e).__name__ + ": " + str(e)
        traceback.print_exc(file=_stderr)
except Exception as e:
    _error = type(e).__name__ + ": " + str(e)
    traceback.print_exc(file=_stderr)
finally:
    sys.stdout = _old_out
    sys.stderr = _old_err

json.dumps({
    "frames": _frames,
    "error": _error,
    "stdout": _stdout.getvalue(),
    "stderr": _stderr.getvalue(),
})
`.trim();
}

function formatCapturedOutput(stdout, stderr) {
  const out = String(stdout ?? "");
  const err = String(stderr ?? "");
  if (out && err) return `${out}${out.endsWith("\n") ? "" : "\n"}${err}`;
  return out || err;
}

/**
 * Right-hand viz: pixel-art grid + Play / Pause. Locks the Python editor
 * while playing. Only the live image is shown — each in-place write paints
 * one cell.
 *
 * @param {HTMLElement} container
 * @param {{
 *   editor: object,
 *   pixelArray?: string[][],
 *   start?: [number, number],
 *   color?: string,
 *   stepDelayMs?: number,
 * }} [options]
 */
export function mountFloodFillViz(container, options = {}) {
  if (!container) return null;

  const original = clonePixelArray(options.pixelArray ?? PIXEL_ARRAY);
  const stepDelayMs = options.stepDelayMs ?? 28;
  const editor = options.editor ?? null;
  const getCode = options.getCode ?? (() => editor?.getCode?.() ?? "");

  let start = options.start ? options.start.slice() : DEFAULT_START.slice();
  let fillColor = options.color ?? DEFAULT_COLOR;
  let liveGrid = clonePixelArray(original);
  let frames = [];
  let frameIndex = -1;
  let playing = false;
  let playTimer = null;
  let compiling = false;
  let statusOverride = null;
  let lastOutput = { text: "", isError: false };

  container.innerHTML = "";
  container.classList.remove("cb-viz-placeholder");
  container.classList.add("iv-root", "dr-viz-root", "ff-viz-root");

  const heading = document.createElement("div");
  heading.className = "adj-heading";
  heading.textContent = "Pixel grid";
  container.appendChild(heading);

  const toolbar = document.createElement("div");
  toolbar.className = "ff-toolbar";
  toolbar.innerHTML = `
    <div class="ff-readout" data-role="readout"></div>
    <label class="ff-color-field">
      Fill colour
      <input type="color" data-role="fill-color" value="${fillColor}">
      <span class="ff-hex" data-role="fill-hex">${fillColor}</span>
    </label>
  `;
  container.appendChild(toolbar);

  const hint = document.createElement("p");
  hint.className = "adj-hint";
  hint.textContent = "Click a pixel to choose the start cell. Hover a cell to read its colour.";
  container.appendChild(hint);

  const gridMount = document.createElement("div");
  container.appendChild(gridMount);

  const status = document.createElement("div");
  status.className = "ht-play-status";
  container.appendChild(status);

  const controls = document.createElement("div");
  controls.className = "ht-quiz-controls";
  container.appendChild(controls);

  const board = mountPixelBoard(gridMount, liveGrid, {
    start,
    selectable: true,
    onCellClick: (r, c) => {
      if (playing || compiling) return;
      start = [r, c];
      frames = [];
      frameIndex = -1;
      statusOverride = null;
      resetImage();
      updateReadout();
      renderStatus();
      renderControls();
    },
  });

  const readoutEl = toolbar.querySelector('[data-role="readout"]');
  const colorInput = toolbar.querySelector('[data-role="fill-color"]');
  const fillHexEl = toolbar.querySelector('[data-role="fill-hex"]');

  colorInput.addEventListener("input", () => {
    fillColor = colorInput.value;
    fillHexEl.textContent = fillColor;
    frames = [];
    frameIndex = -1;
    statusOverride = null;
    resetImage();
    renderStatus();
    renderControls();
  });

  gridMount.addEventListener("pointermove", (event) => {
    const cell = event.target.closest?.(".ff-cell");
    if (!cell) return;
    updateReadout(cell.dataset.hex, Number(cell.dataset.row), Number(cell.dataset.col));
  });

  function startHex() {
    return liveGrid[start[0]]?.[start[1]] ?? original[start[0]]?.[start[1]] ?? "";
  }

  function updateReadout(hoverHex, hoverR, hoverC) {
    const hex = hoverHex ?? startHex();
    const r = hoverR ?? start[0];
    const c = hoverC ?? start[1];
    const isStart = r === start[0] && c === start[1];
    readoutEl.innerHTML = isStart
      ? `Start <span class="ff-hex">(${r}, ${c})</span> · <span class="ff-hex">${hex}</span>`
      : `<span class="ff-hex">(${r}, ${c})</span> · <span class="ff-hex">${hex}</span>`;
  }

  function clearPlayTimer() {
    if (playTimer != null) {
      clearTimeout(playTimer);
      playTimer = null;
    }
  }

  function stopPlayback() {
    playing = false;
    clearPlayTimer();
  }

  function currentFrame() {
    if (frameIndex < 0 || frameIndex >= frames.length) return null;
    return frames[frameIndex];
  }

  function resetImage() {
    liveGrid = clonePixelArray(original);
    board.setGrid(liveGrid);
    board.setStart(start);
    board.setPaint(null);
  }

  function applyFrame(frame) {
    if (!frame || frame.r == null) return;
    liveGrid[frame.r][frame.c] = frame.color;
    board.setColor(frame.r, frame.c, frame.color);
    board.setPaint([frame.r, frame.c]);
  }

  function renderStatus() {
    const frame = currentFrame();
    if (statusOverride) {
      status.textContent = statusOverride;
      status.classList.toggle("ht-play-status-warn", true);
      status.classList.toggle("ht-play-status-ok", false);
      return;
    }
    status.classList.toggle("ht-play-status-warn", false);
    status.classList.toggle("ht-play-status-ok", false);
    if (!frame) {
      status.textContent = "Click a pixel, pick a fill colour, then press Play.";
      return;
    }
    if (frame.done) {
      const painted = frames.filter((f) => !f.done).length;
      status.textContent = painted
        ? `Fill complete — ${painted} pixel${painted === 1 ? "" : "s"} painted.`
        : "Your function ran but did not change any cells.";
      status.classList.toggle("ht-play-status-ok", painted > 0);
      status.classList.toggle("ht-play-status-warn", painted === 0);
      return;
    }
    status.textContent = `Painting (${frame.r}, ${frame.c}) → ${frame.color}`;
  }

  function renderEditorChrome(frame) {
    if (!editor) return;
    if (frame?.line != null && Number.isFinite(frame.line)) editor.highlightLine(frame.line);
    else editor.clearLineHighlight?.();
  }

  function render() {
    const frame = currentFrame();
    if (frameIndex < 0) {
      resetImage();
    } else if (frame && !frame.done) {
      // Play ticks apply one cell at a time; jumping (reset) rebuilds.
    } else if (frame?.done) {
      board.setPaint(null);
    }
    updateReadout();
    renderStatus();
    renderEditorChrome(frame);
    renderControls();
  }

  async function compileFrames() {
    const userSrc = (getCode() || "").trim();
    if (!userSrc) {
      statusOverride = "The editor is empty — write floodFill first.";
      frames = [];
      frameIndex = -1;
      return false;
    }
    if (!/\bdef\s+floodFill\s*\(/.test(userSrc)) {
      statusOverride = "Define a floodFill(pixel_array, start, color) function.";
      frames = [];
      frameIndex = -1;
      return false;
    }

    compiling = true;
    statusOverride = null;
    status.textContent = "Loading Python runtime…";
    status.classList.remove("ht-play-status-warn", "ht-play-status-ok");
    renderControls();

    try {
      const pyodide = await getPyodide();
      status.textContent = "Running your code…";
      const rawJson = await pyodide.runPythonAsync(
        buildFloodHarness(original, start, fillColor, userSrc)
      );
      const payload = JSON.parse(typeof rawJson === "string" ? rawJson : String(rawJson));
      const captured = formatCapturedOutput(payload.stdout, payload.stderr);
      lastOutput = { text: captured, isError: !!payload?.error };

      const rawFrames = Array.isArray(payload.frames) ? payload.frames : [];
      frames = rawFrames.map((ev) => ({
        r: ev.r,
        c: ev.c,
        color: ev.color,
        line: ev.line == null || ev.line === "" ? null : Number(ev.line),
        done: false,
      }));
      frames.push({ done: true, line: null });

      if (payload?.error === "TOO_MANY_ITERS") {
        statusOverride = "Loop ran too long — did you stop when the region is filled?";
        frameIndex = -1;
        if (captured) editor?.setStdout?.(captured, { isError: true });
        return frames.length > 1;
      }
      if (payload?.error) {
        statusOverride = "Error running code: " + payload.error;
        frameIndex = -1;
        editor?.setStdout?.(captured || payload.error, { isError: true });
        return frames.length > 1;
      }

      statusOverride = null;
      frameIndex = -1;
      if (captured) editor?.setStdout?.(captured, { isError: false });
      return true;
    } catch (err) {
      console.error(err);
      statusOverride = "Error running code: " + String(err);
      frames = [];
      frameIndex = -1;
      lastOutput = { text: String(err), isError: true };
      editor?.setStdout?.(String(err), { isError: true });
      return false;
    } finally {
      compiling = false;
    }
  }

  async function play() {
    const atEnd = frames.length > 0 && frameIndex >= frames.length - 1;
    const needCompile = !frames.length || atEnd || frameIndex < 0;
    if (needCompile) {
      editor?.lock();
      const ok = await compileFrames();
      if (!ok) {
        editor?.unlock();
        resetImage();
        render();
        return;
      }
      resetImage();
      frameIndex = -1;
    }
    editor?.lock();
    playing = true;
    renderControls();

    const tick = () => {
      if (!playing) return;
      if (frameIndex >= frames.length - 1) {
        stopPlayback();
        render();
        return;
      }
      frameIndex += 1;
      const frame = currentFrame();
      if (frame && !frame.done) applyFrame(frame);
      else board.setPaint(null);
      updateReadout();
      renderStatus();
      renderEditorChrome(frame);
      if (playing && frameIndex < frames.length - 1) {
        playTimer = setTimeout(tick, stepDelayMs);
      } else {
        stopPlayback();
        render();
      }
    };
    playTimer = setTimeout(tick, stepDelayMs);
  }

  function pause() {
    stopPlayback();
    renderControls();
  }

  function reset() {
    stopPlayback();
    frames = [];
    frameIndex = -1;
    statusOverride = null;
    lastOutput = { text: "", isError: false };
    editor?.unlock();
    editor?.clearLineHighlight?.();
    editor?.clearStdout?.();
    resetImage();
    render();
  }

  const playBtn = document.createElement("button");
  playBtn.type = "button";
  playBtn.className = "ht-nav-btn";
  playBtn.addEventListener("click", () => {
    if (playing) pause();
    else play();
  });

  const resetBtn = document.createElement("button");
  resetBtn.type = "button";
  resetBtn.className = "ht-nav-btn ht-nav-btn-ghost";
  resetBtn.textContent = "Reset";
  resetBtn.addEventListener("click", () => reset());

  controls.append(playBtn, resetBtn);

  function renderControls() {
    playBtn.textContent = compiling ? "Loading…" : playing ? "Pause" : "Play";
    playBtn.disabled = compiling;
  }

  updateReadout();
  renderStatus();
  renderControls();
  getPyodide().catch(() => {});

  const ro = typeof ResizeObserver === "function"
    ? new ResizeObserver(() => board.resize(gridMount.clientWidth))
    : null;
  ro?.observe(container);

  return {
    play,
    pause,
    reset,
    destroy: () => {
      stopPlayback();
      ro?.disconnect();
    },
  };
}
